package database

import (
	"bytes"
	"fmt"
	"maps"
	"os"
	"slices"
	"text/template"

	"github.com/wowsims/forever/sim/core"
	"github.com/wowsims/forever/sim/core/proto"
)

const simTablesTSOutputPath = "ui/sim/proto/sim_tables_auto_gen.ts"

type tsItemTypeSlots struct {
	ItemTypeName  string
	ItemSlotNames []string
}

type tsPseudoStatRating struct {
	PseudoStatName string
	RatingName     string
	PerPercent     float64
	Fallback       bool
}

type tsRatingChannels struct {
	RatingName   string
	ChannelNames []string
	PerPercent   float64
}

type tsSimTables struct {
	ItemTypeToSlots        []tsItemTypeSlots
	SharpWeaponTypes       []string
	BluntWeaponTypes       []string
	DenseSharpeningStoneID int32
	DenseWeightstoneID     int32
	PseudoStatRatings      []tsPseudoStatRating
	RatingChannels         []tsRatingChannels
}

const simTablesTSTemplate = `// Code generated by tools/database/gen_sim_tables_ts.go. DO NOT EDIT.

import { ItemSlot, ItemType, PseudoStat, Stat, WeaponType } from '@generated/proto/common';

// The slots an item of each non-weapon type can occupy.
export const ITEM_TYPE_TO_SLOTS: Partial<Record<ItemType, ItemSlot[]>> = {
{{- range .ItemTypeToSlots }}
	[ItemType.{{ .ItemTypeName }}]: [{{ range $index, $slot := .ItemSlotNames }}{{ if $index }}, {{ end }}ItemSlot.{{ $slot }}{{ end }}],
{{- end }}
};

export const SHARP_WEAPON_TYPES: WeaponType[] = [{{ range $index, $type := .SharpWeaponTypes }}{{ if $index }}, {{ end }}WeaponType.{{ $type }}{{ end }}];

export const BLUNT_WEAPON_TYPES: WeaponType[] = [{{ range $index, $type := .BluntWeaponTypes }}{{ if $index }}, {{ end }}WeaponType.{{ $type }}{{ end }}];

export const DENSE_SHARPENING_STONE_ID = {{ .DenseSharpeningStoneID }};

export const DENSE_WEIGHTSTONE_ID = {{ .DenseWeightstoneID }};

// The rating that converts into each percent pseudo stat with one, at perPercent rating per percent
// point. Outside the rating channels, a percent with fallback set and no weight of its own is worth
// its rating's weight.
export const PSEUDO_STAT_RATINGS: Partial<Record<PseudoStat, { rating: Stat; perPercent: number; fallback: boolean }>> = {
{{- range .PseudoStatRatings }}
	[PseudoStat.{{ .PseudoStatName }}]: { rating: Stat.{{ .RatingName }}, perPercent: {{ .PerPercent }}, fallback: {{ .Fallback }} },
{{- end }}
};

// The melee, ranged and spell percents one hit, crit or haste rating raises together, at perPercent
// rating per percent point. Each percent's weight measures its own channel alone: melee attacks,
// ranged attacks or spells.
export const RATING_CHANNELS: { rating: Stat; channels: [PseudoStat, PseudoStat, PseudoStat]; perPercent: number }[] = [
{{- range .RatingChannels }}
	{
		rating: Stat.{{ .RatingName }},
		channels: [{{ range $index, $channel := .ChannelNames }}{{ if $index }}, {{ end }}PseudoStat.{{ $channel }}{{ end }}],
		perPercent: {{ .PerPercent }},
	},
{{- end }}
];
`

// protoEnumName panics on a value the proto enum does not define, so the generator never writes a bare
// `ItemType.` into the UI.
func protoEnumName[T ~int32](names map[int32]string, value T) string {
	name, ok := names[int32(value)]
	if !ok {
		panic(fmt.Sprintf("no proto enum name for %T %d", value, value))
	}
	return name
}

func protoEnumNames[T ~int32](names map[int32]string, values []T) []string {
	result := make([]string, 0, len(values))
	for _, value := range values {
		result = append(result, protoEnumName(names, value))
	}
	return result
}

func simTablesTSData() tsSimTables {
	data := tsSimTables{
		SharpWeaponTypes:       protoEnumNames(proto.WeaponType_name, core.SharpWeaponTypes),
		BluntWeaponTypes:       protoEnumNames(proto.WeaponType_name, core.BluntWeaponTypes),
		DenseSharpeningStoneID: core.DenseSharpeningStoneID,
		DenseWeightstoneID:     core.DenseWeightstoneID,
	}

	for _, itemType := range slices.Sorted(maps.Keys(core.ItemTypeToSlotsMap)) {
		data.ItemTypeToSlots = append(data.ItemTypeToSlots, tsItemTypeSlots{
			ItemTypeName:  protoEnumName(proto.ItemType_name, itemType),
			ItemSlotNames: protoEnumNames(proto.ItemSlot_name, core.ItemTypeToSlotsMap[itemType]),
		})
	}

	for idx := range len(proto.PseudoStat_name) {
		if rating, ok := core.RatingPercentOf(proto.PseudoStat(idx)); ok {
			data.PseudoStatRatings = append(data.PseudoStatRatings, tsPseudoStatRating{
				PseudoStatName: protoEnumName(proto.PseudoStat_name, rating.Percent),
				RatingName:     protoEnumName(proto.Stat_name, proto.Stat(rating.Rating)),
				PerPercent:     rating.RatingPerPercent,
				Fallback:       rating.Root,
			})
		}
	}
	for _, channels := range core.RatingChannelTable {
		data.RatingChannels = append(data.RatingChannels, tsRatingChannels{
			RatingName:   protoEnumName(proto.Stat_name, proto.Stat(channels.Rating)),
			ChannelNames: protoEnumNames(proto.PseudoStat_name, channels.Channels()),
			PerPercent:   channels.RatingPerPercent,
		})
	}

	return data
}

// GenerateSimTablesTSFile writes the sim's item slot and weapon tables that the UI reads.
func GenerateSimTablesTSFile() error {
	tpl, err := template.New("simTablesTS").Parse(simTablesTSTemplate)
	if err != nil {
		return fmt.Errorf("failed to parse sim tables TS template: %w", err)
	}

	var buf bytes.Buffer
	if err := tpl.Execute(&buf, simTablesTSData()); err != nil {
		return fmt.Errorf("failed to execute sim tables TS template: %w", err)
	}

	if err := os.WriteFile(simTablesTSOutputPath, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to write generated sim tables TS file: %w", err)
	}

	return nil
}
