package database

import (
	"fmt"
	"go/format"
	"maps"
	"os"
	"reflect"
	"slices"
	"strings"

	"github.com/wowsims/forever/sim/core/proto"
)

const consumablesTableFileName = "sim/core/consumables_auto_gen.go"

// Every consumable the database ships and the spell effects they name, as the sim reads them:
// flask, elixir and food stats and durations, and the resource gains and aura stats of potions and
// conjured items.
func GenerateConsumablesTable(consumables map[int32]*proto.Consumable, spellEffects map[int32]*proto.SpellEffect) error {
	var b strings.Builder
	b.WriteString("// Code generated by tools/database/gen_db. DO NOT EDIT.\n\n")
	b.WriteString("package core\n\n")
	b.WriteString("import \"github.com/wowsims/forever/sim/core/proto\"\n\n")
	writeProtoTable(&b, "consumableTable", consumables)
	writeProtoTable(&b, "spellEffectTable", spellEffects)

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("the generated consumables table does not parse, refusing to write it: %w", err)
	}

	if err := os.WriteFile(consumablesTableFileName, out, 0644); err != nil {
		return fmt.Errorf("failed to write file %s: %w", consumablesTableFileName, err)
	}

	return nil
}

// One message per line, in ID order.
func writeProtoTable[T any](b *strings.Builder, name string, table map[int32]*T) {
	fmt.Fprintf(b, "var %s = map[int32]*%s{\n", name, reflect.TypeFor[T]().String())
	for _, id := range slices.Sorted(maps.Keys(table)) {
		fmt.Fprintf(b, "%d: %s,\n", id, protoLiteral(reflect.ValueOf(table[id]), true))
	}
	b.WriteString("}\n\n")
}
